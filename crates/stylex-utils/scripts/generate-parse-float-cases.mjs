/** Rust string-literal escaping, kept to ASCII so the table stays readable. */
function rustLiteral(input) {
  let out = '"';
  for (const ch of input) {
    const code = ch.codePointAt(0);
    if (ch === '"' || ch === '\\') out += `\\${ch}`;
    else if (ch === '\t') out += '\\t';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (code < 0x20 || code > 0x7e) out += `\\u{${code.toString(16)}}`;
    else out += ch;
  }
  return `${out}"`;
}

/** `Option<f64>` spelled so that Rust parses back the exact same bits. */
function rustExpectation(value) {
  if (Number.isNaN(value)) return 'None';
  if (value === Infinity) return 'Some(f64::INFINITY)';
  if (value === -Infinity) return 'Some(f64::NEG_INFINITY)';
  if (Object.is(value, -0)) return 'Some(-0.0)';
  const spelled =
    Number.isInteger(value) && Math.abs(value) < 1e21 ? `${value}.0` : value.toExponential();
  return `Some(${spelled})`;
}

const rows = INPUTS.map(
  input => `  (${rustLiteral(input)}, ${rustExpectation(Number.parseFloat(input))}),`
);

